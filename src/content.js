export function levelFor(xp) {
  const steps = [
    [0, "Μόλις μπήκες"],
    [40, "Ξέρει πού κοιμάται"],
    [90, "Κρατά ρυθμό"],
    [150, "Ξέρει ποιον να ρωτήσει"],
    [220, "Βοηθά τον διπλανό"],
    [300, "Σταθερός μέσα"],
  ];
  let current = steps[0];
  for (const step of steps) if (xp >= step[0]) current = step;
  return { xp, name: current[1], next: steps.find((s) => s[0] > xp)?.[0] ?? 300 };
}

