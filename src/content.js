export function levelFor(xp) {
  const steps = [
    [0, "Πολίτης με απορίες"],
    [40, "Το σημείωμα στο χέρι"],
    [90, "Η τσάντα κλείνει"],
    [150, "Πρώτη νύχτα"],
    [220, "Ξέρει ποιον να ρωτήσει"],
    [300, "Έτοιμος να παρουσιαστεί"],
  ];
  let current = steps[0];
  for (const step of steps) if (xp >= step[0]) current = step;
  return { xp, name: current[1], next: steps.find((s) => s[0] > xp)?.[0] ?? 300 };
}

export function personalLine(state) {
  const worry = worries.find((w) => w.id === state.worries[0]);
  const aim = aims.find((a) => a.id === state.aim);
  const place = state.country === "cy" ? "στην Εθνική Φρουρά" : "στον Στρατό Ξηράς";
  if (!state.onboarded) return `Διάλεξε χώρα και πες τι σε απασχολεί. Ο χάρτης φτιάχνεται για σένα, ${place}.`;
  const focus = worry ? ` Πρώτα κοιτάμε: ${worry.label}.` : "";
  const goal = aim ? ` Στόχος: ${aim.label}.` : "";
  return `Ο χάρτης σου ${place} είναι έτοιμος.${focus}${goal}`;
}

